        // The robust slice-based typewriter logic
        typeIntervalRef.current = setInterval(() => {
            currentChars += 8; // Speed of typing (8 characters per tick)
            
            if (currentChars >= totalChars) {
                currentChars = totalChars;
                setIsTypingComplete(true);
                clearInterval(typeIntervalRef.current);
            }
            
            setTypedCharsCount(currentChars);
            setTypingProgress((currentChars / totalChars) * 100);
            
        }, 20); // 20ms delay

